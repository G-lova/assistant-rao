def digest(detected_type: Optional[str], fz: Optional[int]) -> str:
    """Выжимка норм для типа документа и закона закупки.

    Args:
        detected_type: Тип документа.
        fz: 44 / 223 / ``None``.

    Returns:
        str: Текст для запроса (пустая строка — выжимки для типа нет).
    """
    if fz == 223:
        return COMMON_223
    specific = BY_TYPE_44.get(detected_type or "")
    if not specific:
        return COMMON_44 if fz == 44 else ""
    return specific + "\n" + COMMON_44


def version(detected_type: Optional[str], fz: Optional[int]) -> str:
    """Короткий хэш выжимки (часть ключа кэша риск-анализа)."""
    return hashlib.sha256(digest(detected_type, fz).encode("utf-8")).hexdigest()[:8]
