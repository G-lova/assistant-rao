"""Прототип проверки критерия мониторинга «Соблюдение требований к описанию объекта закупки (ТЗ)».

Работает по полному тексту договора/контракта (получает вызывающий код). Правила выведены из
итоговых заключений: чаще всего нарушением названо отсутствие в договоре срока и порядка приёмки
или оплаты услуг (ст. 720, 781, 783 ГК РФ) и отсутствие требования о лицензии на охранную
деятельность (ст. 11.2 Закона РФ № 2487-1). Правила проверяют ОТСУТСТВИЕ условия, поэтому
цитата берётся из предмета договора (доказывает, что текст прочитан и относится к услугам).
Если текст короток (скан распознан не полностью), вердикт не выдаётся.
"""

import re
from typing import Dict, List

from knowledge_store.monitoring_nmck import Finding, norm

MIN_CONTRACT_CHARS = 3000  # короче — вероятно, распознана лишь часть скана: вывод об отсутствии условий ненадёжен

# Признаки наличия условий в тексте договора
# Приёмка считается установленной, если рядом с ней указан срок («в течение 5 рабочих дней», «не позднее …»);
# одного упоминания «документа о приёмке» недостаточно (ст. 720, 783 ГК РФ требуют срок и порядок)
_RE_ACCEPT = re.compile(
    r"(прием\w*|приём\w*)[^.]{0,200}(в течение|не позднее|в срок|\d+\s*(\(\w+\)\s*)?(рабоч|календарн)?\w*\s*дн)|"
    r"(в течение|не позднее|\d+\s*(\(\w+\)\s*)?(рабоч|календарн)?\w*\s*дн)[^.]{0,200}(прием\w*|приём\w*)", re.I)
_RE_PAYMENT = re.compile(r"оплач?т?\w+[^.]{0,200}(в течение|не позднее|в срок)|"
                         r"(в течение|не позднее)[^.]{0,120}оплач?т?\w+|порядок\w* оплат\w+|порядок\w* расч[её]т\w+", re.I)
# Автоформа ЕИС содержит только реквизиты; условия приёмки/оплаты/лицензии — в приложенном тексте контракта
_RE_EIS_STUB = re.compile(r"электронн\w+ (версия контракта|контракт,? сформированный)", re.I)
_RE_SUBJECT = re.compile(r"предмет\w* (договора|контракта)[^.]{0,250}", re.I)
_RE_SECURITY = re.compile(r"охран\w+", re.I)
# Требование о лицензии — не упоминание в шапке/реквизитах, а обязанность или условие («наличие действующей лицензии»)
_RE_LICENSE = re.compile(r"(наличи\w+|действующ\w+|обязан\w*[^.]{0,40}(иметь|поддерживать)|гарантир\w+|заверя\w+|"
                         r"имеет|обладает)[^.]{0,80}лиценз\w+", re.I)


def _has_acceptance_term(n: str) -> bool:
    """Есть ли срок приёмки: совпадение с ``_RE_ACCEPT``, не относящееся к оплате.

    Фраза «оплата в течение 7 дней с даты подписания документа о приёмке» задаёт срок оплаты,
    а не приёмки (так было в договорах Ингушского ГУ, где ЭЗ признало приёмку неурегулированной).
    """
    for m in _RE_ACCEPT.finditer(n):
        # контекст: само совпадение и 80 символов до него (в «Оплата … осуществляется в течение …» слово
        # «оплата» стоит перед совпадением)
        ctx = n[max(m.start() - 80, 0):m.end()].lower()
        if "оплат" not in ctx and "оплач" not in ctx:
            return True
    return False


def _subject_quote(n: str) -> str:
    """Цитата из предмета договора (подряд идущие слова) либо начало текста."""
    m = _RE_SUBJECT.search(n)
    return norm(m.group(0))[:200] if m else n[:200]


def check_contract(text: str, ocr: bool = False) -> Dict:
    """Проверяет полный текст договора на наличие обязательных условий.

    Правила:
        * ``NO_ACCEPTANCE_TERMS`` — нет условия о приёмке услуг (приёмка + акт);
        * ``NO_PAYMENT_TERMS`` — нет срока/порядка оплаты;
        * ``NO_LICENSE_REQUIREMENT`` — договор об охране без упоминания лицензии.

    Args:
        text: Полный текст договора (после ``pdftotext``/распознавания).
        ocr: Текст получен распознаванием скана: слова искажены, поэтому правило лицензии
            (ищет конкретную формулировку) не применяется — иначе ложные нарушения.

    Returns:
        dict: ``verdict`` («Соответствует»/«Не соответствует»/«Недостаточно данных»),
        ``findings`` (с цитатой из предмета договора), ``chars`` (длина текста).
    """
    n = norm(text)
    if len(n) < MIN_CONTRACT_CHARS:
        return {"verdict": "Недостаточно данных", "findings": [], "chars": len(n)}
    if _RE_EIS_STUB.search(n[:400]):
        return {"verdict": "Недостаточно данных", "findings": [], "chars": len(n),
                "reason": "автоформа ЕИС без текста условий контракта"}
    quote = _subject_quote(n)
    findings: List[Finding] = []
    if not _has_acceptance_term(n):
        findings.append(Finding("NO_ACCEPTANCE_TERMS",
                                "В договоре не установлен срок и порядок приёмки оказанных услуг "
                                "(ст. 720, 783 ГК РФ)", [], quote))
    if not _RE_PAYMENT.search(n):
        findings.append(Finding("NO_PAYMENT_TERMS",
                                "В договоре не установлен срок и порядок оплаты оказанных услуг "
                                "(ст. 781 ГК РФ)", [], quote))
    if not ocr and _RE_SECURITY.search(n[:3000]) and not _RE_LICENSE.search(n):
        findings.append(Finding("NO_LICENSE_REQUIREMENT",
                                "В договоре отсутствует требование о наличии у исполнителя лицензии на частную "
                                "охранную деятельность (ст. 11.2 Закона РФ № 2487-1)", [], quote))
    return {"verdict": "Не соответствует" if findings else "Соответствует",
            "findings": [f.__dict__ for f in findings], "chars": len(n)}
