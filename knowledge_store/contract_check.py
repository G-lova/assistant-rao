"""Детерминированный детектор типичных нарушений проекта контракта (критерии 2.5 и 3.7 сводного ЭЗ).

Эксперты в критерии 2.5 («Соответствие проекта контракта действующему законодательству») называют повторяющиеся
нарушения. Модуль ищет их по тексту проекта контракта регулярными выражениями, без LLM:

* ``e_acceptance`` — нет электронной приёмки через ЕИС (ч. 13 ст. 94 44-ФЗ);
* ``e_notices`` — нет обмена уведомлениями при мерах ответственности через ЕИС (ч. 16 ст. 94 44-ФЗ);
* ``ks_forms`` — приёмка по формам КС-2/КС-3 вместо документа о приёмке в ЕИС (ч. 13 ст. 94);
* ``pay_on_funds`` — оплата «по мере поступления денежных средств» (ст. 34 44-ФЗ);
* ``bank_guarantee`` — «банковская гарантия» вместо независимой (ст. 45, ч. 3 ст. 96);
* ``price_right_fine`` — ответственность за «цену за право заключения контракта» в конкурсе (ч. 8 ст. 34, ПП № 1042).

Каждое найденное нарушение содержит дословную цитату (или ``None``, если нарушение — отсутствие положения),
норму и пояснение. Отсутствие положения проверяется только если текст контракта достаточно длинный:
на огрызке документа «нет электронной приёмки» ничего не доказывает.
"""
import re
from typing import Any, Dict, List, Optional

CONTRACT_KEY = "field2_2_5"          # 2.5. Соответствие проекта контракта законодательству
DOCUMENTATION_KEY = "field2_3_7"     # 3.7. Соответствие документации требованиям 44-ФЗ
# Сильные признаки: на эталоне экспертов 9 срабатываний из 10 пришлись на «0» в 2.5. Слабые (e_notices, price_right_fine)
# срабатывают почти на каждом контракте (точность ~64% при базовой доле «0» 58%): сами по себе «0» не дают,
# но добавляются в текст замечания, когда есть сильный признак.
STRONG_CODES = frozenset({"e_acceptance", "pay_on_funds", "bank_guarantee", "ks_forms"})
MIN_CONTRACT_CHARS = 6000            # короче — это не полный проект контракта
CONTRACT_CODES = ("docContractDoWorkFiles", "docContractNIRFiles", "docContractPostTovarFiles",
                  "docContractFiles", "docContractProjectFiles")

_EIS = r"(?:единой\s+информационной\s+системе|\bЕИС\b)"
_E_ACCEPT = re.compile(rf"(?:документ\w*\s+о\s+приемк\w*[^.]{{0,200}}{_EIS}|{_EIS}[^.]{{0,200}}документ\w*\s+о\s+приемк\w*|"
                       rf"электронн\w+\s+(?:акт|документ)\w*[^.]{{0,100}}приемк|электронн\w+\s+приемк|"
                       rf"приемк\w+[^.]{{0,120}}в\s+электронной\s+форме)", re.I)
_E_NOTICE = re.compile(rf"(?:мер\w*\s+ответственност\w+[^.]{{0,300}}(?:{_EIS}|электронн)|(?:{_EIS}|электронн\w+\s+уведомлени)[^.]{{0,300}}мер\w*\s+ответственност|"
                       rf"электронн\w+\s+уведомлени\w+[^.]{{0,200}}(?:нарушени|ответственност)|"
                       rf"нарушени\w+[^.]{{0,200}}электронн\w+\s+уведомлени)", re.I)
_KS_FORMS = re.compile(r"[^.\n]{0,120}\b(?:КС-?\s?2|КС-?\s?3)\b[^.\n]{0,160}", re.I)
_PAY_ON_FUNDS = re.compile(r"[^.\n]{0,120}по\s+мере\s+(?:поступлени\w+|финансировани\w+|выделени\w+)[^.\n]{0,160}", re.I)
_BANK_GUARANTEE = re.compile(r"[^.\n]{0,100}банковск\w+\s+гаранти\w+[^.\n]{0,100}", re.I)
_PRICE_RIGHT = re.compile(r"[^.\n]{0,160}(?:наиболее\s+высок\w+\s+цен\w+\s+за\s+право|за\s+право\s+заключ\w+\s+контракт)[^.\n]{0,160}", re.I)
_PENALTY_ARTICLE = re.compile(r"1042|штраф|пен[яи]|неустойк", re.I)


def is_contract(doc: Dict[str, Any]) -> bool:
    """Документ — проект контракта: по коду типа, иначе по имени файла."""
    if doc.get("doc_code") in CONTRACT_CODES:
        return True
    name = str(doc.get("filename") or "")
    return bool(re.search(r"контракт|договор", name, re.I)) and not re.search(r"ЭЗ_|заключени", name, re.I)


def _cut(original: str, match: "re.Match") -> str:
    """Фрагмент оригинального текста по позициям совпадения."""
    return original[match.start():match.end()]


def _clip(text: str, limit: int = 300) -> str:
    """Цитата без лишних пробелов, не длиннее ``limit``."""
    return re.sub(r"\s+", " ", text).strip()[:limit]


def check_contract(text: Optional[str], competition: bool = False) -> List[Dict[str, Any]]:
    """Нарушения в тексте проекта контракта.

    Args:
        text: Полный текст проекта контракта.
        competition: Закупка проводится конкурсом (не аукционом): тогда ответственность за «цену за право
            заключения контракта» — нарушение (контракт за плату возможен только в электронном аукционе).

    Returns:
        list[dict]: ``{"code", "issue", "quote", "norm"}``; ``quote`` — ``None``, если нарушение состоит
        в отсутствии положения. Пустой список — нарушений из перечня не найдено или текст слишком короткий.
    """
    original = text or ""
    if len(original) < MIN_CONTRACT_CHARS:
        return []
    text = original.replace("ё", "е").replace("Ё", "Е")      # длина не меняется: цитаты берутся из оригинала по позициям
    found: List[Dict[str, Any]] = []

    def add(code: str, issue: str, norm: str, quote: Optional[str] = None) -> None:
        """Добавляет находку."""
        found.append({"code": code, "issue": issue, "norm": norm, "quote": _clip(quote) if quote else None})

    if not _E_ACCEPT.search(text):
        ks = _KS_FORMS.search(text)
        add("e_acceptance", "в проекте контракта не предусмотрена приёмка с формированием документа о приёмке в ЕИС",
            "ч. 13 ст. 94 Закона № 44-ФЗ", original[ks.start():ks.end()] if ks else None)
    elif _KS_FORMS.search(text) and not re.search(r"документ\w*\s+о\s+приемк", text, re.I):
        add("ks_forms", "приёмка оформляется актом по формам КС-2/КС-3 вместо документа о приёмке в ЕИС",
            "ч. 13 ст. 94 Закона № 44-ФЗ", _cut(original, _KS_FORMS.search(text)))
    if _PENALTY_ARTICLE.search(text) and not _E_NOTICE.search(text):
        add("e_notices", "не предусмотрен обмен документами при применении мер ответственности и иных действий "
                         "в связи с нарушением условий контракта через ЕИС путём направления электронных уведомлений",
            "ч. 16 ст. 94 Закона № 44-ФЗ")
    m = _PAY_ON_FUNDS.search(text)
    if m:
        add("pay_on_funds", "срок оплаты поставлен в зависимость от поступления денежных средств", "ст. 34 Закона № 44-ФЗ", original[m.start():m.end()])
    m = _BANK_GUARANTEE.search(text)
    if m:
        add("bank_guarantee", "обеспечение названо «банковской гарантией», а не независимой гарантией; "
                              "гарантия может быть выдана не только банком", "ст. 45, ч. 3 ст. 96 Закона № 44-ФЗ", original[m.start():m.end()])
    m = _PRICE_RIGHT.search(text) if competition else None
    if m:
        add("price_right_fine", "ответственность за цену за право заключения контракта установлена в закупке, "
                                "где контракт за плату не заключается", "ч. 8 ст. 34 Закона № 44-ФЗ, п. 5 Правил ПП № 1042", original[m.start():m.end()])
    return found
