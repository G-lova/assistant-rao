"""Закон текущей экспертизы (44-ФЗ или 223-ФЗ) для промптов и текстов заключения.

Промпты и шаблоны написаны под 44-ФЗ. Для 223-ФЗ они должны ссылаться на 223-ФЗ, а нарушения, специфичные для 44-ФЗ
(электронная приёмка по ч. 13 ст. 94, ст. 34, ПП № 1042 и т. п.), не проверяются. Закон хранится в контекстной
переменной (:data:`current_law`): её значение наследуют все задачи ``asyncio``, созданные после установки, поэтому
не нужно протаскивать параметр через десятки функций. Устанавливается по коду формы (:func:`set_from_form`) в начале
извлечения фактов и сборки заключения.
"""
from contextvars import ContextVar
from typing import Optional

LAW_44 = "44-ФЗ"
LAW_223 = "223-ФЗ"

current_law: ContextVar[str] = ContextVar("pe_current_law", default=LAW_44)

LAW_TITLES = {
    LAW_44: ("Федерального закона от 05.04.2013 № 44-ФЗ «О контрактной системе в сфере закупок товаров, работ, услуг "
             "для обеспечения государственных и муниципальных нужд»"),
    LAW_223: ("Федерального закона от 18.07.2011 № 223-ФЗ «О закупках товаров, работ, услуг отдельными видами "
              "юридических лиц»"),
}


def law_of_form(form_code: Optional[str]) -> str:
    """Закон по коду формы: ``223fz_…`` → 223-ФЗ, остальное (в том числе ``None``) → 44-ФЗ."""
    return LAW_223 if (form_code or "").startswith("223fz") else LAW_44


def set_from_form(form_code: Optional[str]) -> str:
    """Устанавливает закон по коду формы в текущем контексте.

    Args:
        form_code: Код формы (``223fz_competitive_obj6``).

    Returns:
        str: Установленный закон.
    """
    law = law_of_form(form_code)
    current_law.set(law)
    return law


def is_223() -> bool:
    """Идёт ли работа по 223-ФЗ."""
    return current_law.get() == LAW_223


def law_title() -> str:
    """Полное название закона текущей экспертизы (в родительном падеже)."""
    return LAW_TITLES[current_law.get()]


def localize(text: str) -> str:
    """Подставляет закон текущей экспертизы вместо «44-ФЗ» в тексте промпта или шаблона.

    Args:
        text: Текст, написанный под 44-ФЗ.

    Returns:
        str: Тот же текст; для 223-ФЗ каждое «44-ФЗ» заменено на «223-ФЗ».
    """
    return text.replace(LAW_44, LAW_223) if is_223() else text
