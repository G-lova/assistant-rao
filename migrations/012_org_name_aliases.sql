CREATE TABLE IF NOT EXISTS org_name_aliases (
    id         BIGSERIAL PRIMARY KEY,
    alias      TEXT NOT NULL,
    inn        TEXT NOT NULL,
    kpp        TEXT,
    source     TEXT NOT NULL DEFAULT 'learned',     -- users_2026-10-27 | learned
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (alias, inn)
);

CREATE TABLE IF NOT EXISTS expert_org_names (
    env        TEXT   NOT NULL,
    expert_id  BIGINT NOT NULL,
    field      TEXT   NOT NULL,                     -- organization | diplom
    name       TEXT,
    inn        TEXT,
    kpp        TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (env, expert_id, field)
);

